"""Generate appendices/MF_evidence_registers.tex from evidence/FACT_REGISTRY.tsv, CLAIM_SOURCE_MAP.tsv and
SOURCE_MAP.tsv. The appendix is generated: edit the TSV builders, not the .tex file.
Run from the repository root:  python3 -I research_monograph/tools/make_registers_tex.py
"""
import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
EV = ROOT / "research_monograph/evidence"
OUT = ROOT / "research_monograph/appendices/MF_evidence_registers.tex"

UNI = {"Δ": "Delta ", "μ": "mu", "−": "-", "×": "x", "≤": "<=", "≥": ">=", "±": "+-",
       "≈": "~", "→": "->", "Å": "A", "°": " deg", "²": "^2", "³": "^3", "–": "-",
       "—": "-", "‘": "'", "’": "'", "“": '"', "”": '"', "α": "alpha", "γ": "gamma",
       "σ": "sigma", "ε": "eps", "θ": "theta", "₀": "0", "₁": "1", "₂": "2", "₃": "3",
       "√": "sqrt", "…": "...", "′": "'", "µ": "u", " ": " ", " ": " ", "ö": "o",
       "é": "e", "•": "-", "≡": "==", "≠": "!=", "∞": "inf", "τ": "tau", "Θ": "Theta"}
SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
           "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "<": r"\textless{}", ">": r"\textgreater{}"}


def tex(s, n=None):
    s = "".join(UNI.get(c, c) for c in str(s))
    s = "".join(c if ord(c) < 128 else "?" for c in s)
    if n and len(s) > n:
        s = s[: n - 3].rstrip() + "..."
    return "".join(SPECIAL.get(c, c) for c in s)


def rows(name):
    with open(EV / name) as f:
        return list(csv.DictReader(f, delimiter="\t"))


def longtable(caption, label, cols, spec, data):
    head = " & ".join(r"\textbf{" + c + "}" for c in cols)
    out = [r"{\scriptsize", r"\begin{longtable}{@{}" + spec + "@{}}", r"\caption{" + caption + r"}\label{" + label + r"}\\",
           r"\toprule", head + r"\\\midrule\endfirsthead", r"\toprule", head + r"\\\midrule\endhead",
           r"\bottomrule\endfoot"]
    for r in data:
        out.append(" & ".join(r) + r"\\")
    out += [r"\end{longtable}", "}"]
    return "\n".join(out)


facts = rows("FACT_REGISTRY.tsv")
claims = rows("CLAIM_SOURCE_MAP.tsv")
sources = rows("SOURCE_MAP.tsv")
P = lambda w: r">{\raggedright\arraybackslash}p{" + w + "}"

body = [r"% GENERATED by research_monograph/tools/make_registers_tex.py -- do not edit by hand.",
        r"\chapter{Evidence registers}", r"\label{app:mono-registers}", "",
        r"This appendix renders the compact evidence registers of the monograph (\file{research_monograph/evidence/}). "
        r"Facts carry stable identifiers cited in the text as \fact{NNN}; claims of the ledger as \claim{C0NN}; monograph "
        r"synthesis claims as M0NN. The verification column states how each fact was checked: \emph{raw-verified} (the "
        r"value was found at the cited line of the raw Quantum ESPRESSO output), \emph{raw-derived-verified} (recomputed "
        r"from raw geometry), \emph{independent-recompute} (recomputed by a monograph script from the data), "
        r"\emph{derived-from-raw-verified} (a difference of raw-verified values), \emph{json-only} or \emph{log-and-json} "
        r"(taken from the re-derivation outputs or the dated log, not re-checked here), and \emph{ledger-only}. A summary "
        r"is never stronger evidence than its raw source.", ""]
body.append(longtable("Fact registry (\\file{FACT_REGISTRY.tsv}).", "tab:mono-reg-facts",
                      ["ID", "Quantity", "Value", "Label", "Claim", "Verification"],
                      P("1.3cm") + P("5.2cm") + P("3.4cm") + P("1.3cm") + P("1.2cm") + P("2.0cm"),
                      [[tex(f["fact_id"]), tex(f["quantity"], 120), tex(f"{f['value']} {f['units']}".strip(), 90),
                        tex(f["label"]), tex(f["ledger_claim"]), tex(f["verification"], 40)] for f in facts]))
body.append("")
body.append(longtable("Claims (ledger C001--C040 and monograph synthesis claims; \\file{CLAIM_SOURCE_MAP.tsv}).",
                      "tab:mono-reg-claims", ["ID", "Claim (abridged)", "Label", "Facts", "Chapters"],
                      P("1.1cm") + P("8.0cm") + P("1.9cm") + P("1.8cm") + P("2.0cm"),
                      [[tex(c["claim_id"]), tex(c["claim"], 230), tex(c["label"], 30), tex(c["facts"], 40),
                        tex(c["monograph_sections"], 45)] for c in claims]))
body.append("")
body.append(longtable("Source map (\\file{SOURCE_MAP.tsv}); authority 1 = charter or frozen protocol, 7 = working "
                      "hypothesis.", "tab:mono-reg-sources", ["ID", "Path", "Topic", "Auth.", "Status"],
                      P("1.0cm") + P("5.6cm") + P("5.0cm") + P("0.8cm") + P("2.2cm"),
                      [[tex(s["source_id"]), tex(s["path"], 80), tex(s["topic"], 90), tex(s["authority"]),
                        tex(s["status"])] for s in sources]))
OUT.write_text("\n".join(body) + "\n")
print(OUT.relative_to(ROOT), len(facts), "facts,", len(claims), "claims,", len(sources), "sources")
