"""Dry build (text only, NO launch) of the 26-launch diagnostic set of the frozen hypothesis register (register-rev2-frozen-20261010T1833Z,
section 3) and a line diff of every deck against its reference deck. Uses campaign_tools.entry_deck (the construction of
run_atlas.execute / execute_strip; no simulator call, no RUN_INDEX access). Writes s2_prep_decks/<id>_<label>.in and
s2_prep_decks/deck_diffs.txt; prints a summary and the structural checks (exit 1 if any check fails).
  python analysis_2026-10-10_campaign/s2_prep_decks.py"""
import difflib
import re
import sys

import campaign_tools as ct
import make_campaign_configs as mc

OUT = ct.HERE / 's2_prep_decks'
# register section 3, in launch order (section 3 "Order": S2 with S2-11 first; S3 confinement then AFF; IGZO with S3-27; S3-10; S6 after S4c)
DIAG = mc.DIAG + ['S6-13', 'S6-15']
# reference deck(s) per entry: the same-film primary baseline first, then the direct matched control where one exists
REF = {'S2-11': ['S0-02', 'S0-01'], 'S2-04': ['S0-01'], 'S2-06': ['S1-02'], 'S2-03': ['S0-01'], 'S2-01': ['S1-02'], 'S2-02': ['S1-02', 'S2-01'],
       'S2-08': ['S1-02', 'S2-06'], 'S2-12': ['S0-01', 'S2-04'], 'S2-13': ['S1-02', 'S2-06'], 'S2-14': ['S1-02'], 'S2-15': ['S0-01', 'S2-14'],
       'S2-16': ['S2-14'], 'S2-17': ['S2-15'], 'STRIP-6p3': ['S1-01', 'S2-14', 'S2-15'], 'S3-01': ['S0-01', 'AFF-2p0'], 'S3-02': ['S1-01', 'AFF-6p3'],
       'S3-03': ['S1-02'], 'AFF-2p0': ['S0-01'], 'AFF-6p3': ['S1-01'], 'S3-11': ['S0-01'], 'S3-12': ['S1-01'], 'S3-13': ['S1-02'],
       'S3-27': ['S1-01', 'S3-12'], 'S3-10': ['S1-01'], 'S6-13': ['S0-01'], 'S6-15': ['S1-02']}
STORED = {'S0-01': 'run_0061', 'S0-02': 'run_0067', 'S1-01': 'run_0068', 'S1-02': 'run_0069'}   # launched baselines (device.in)
ND0, ND10 = 'thickness_laws.Nd_eff_cm3.Nd0=2.5e+17', 'thickness_laws.Nd_eff_cm3.Nd0=2.5e+18'


def entry(runs, i):
    """matrix campaign_entry; S6-13/S6-15 carry '{frozen model}' (after-calibration entries): built ILLUSTRATIVELY at the S4 start values
    (S0-01 / S1-02 overrides with Nd0 x10, the S6 rule thickness_laws.Nd_eff_cm3.Nd0=2.5e+18)"""
    if i in ('S6-13', 'S6-15'):
        b = runs['S0-01' if i == 'S6-13' else 'S1-02']['campaign_entry']
        return dict(b, id=i, label=f'c10_{i.lower().replace("-", "_")}_{b["label"].rsplit("_", 1)[1]}_ILLUSTRATIVE_start_values',
                    overrides=[ND10 if o == ND0 else o for o in b['overrides']])
    return runs[i]['campaign_entry']


def main():
    mx = ct.matrix(); runs = {r['id']: r for r in mx['runs']}; OUT.mkdir(exist_ok=True)
    txt = {}
    for i in set(DIAG) | {x for v in REF.values() for x in v}:
        txt[i] = ct.entry_deck(entry(runs, i), ct.V3)[0]
    bad = []
    for i, rid in STORED.items():   # the reference decks are the launched ones
        d = next((ct.PKG / 'results' / 'runs').glob(rid + '_*'))
        if (d / 'device.in').read_text() != txt[i]: bad.append(f'{i}: matrix deck differs from {rid}/device.in')
    rep = ['# Deck diffs of the 26-launch diagnostic set (register-rev2-frozen-20261010T1833Z, section 3). Generated by s2_prep_decks.py,',
           '# text only (no launch). Model file config/iwo_material_model_v3.yaml + matrix overrides. "-" = reference deck, "+" = this deck;',
           '# every differing line is listed (comments included). S6-13/S6-15 are ILLUSTRATIVE builds at the S4 start values.', '']
    summary = []
    for n, i in enumerate(DIAG, 1):
        e = entry(runs, i); name = f'{i}_{e["label"]}' + ('_strip' if e.get('mode') == 'strip' else '') + '.in'
        (OUT / name).write_text(txt[i], encoding='ascii')
        rep += ['=' * 100, f'[{n:2d}] {i} ({e["thickness"]} nm{", strip deck" if e.get("mode") == "strip" else ""}) -> s2_prep_decks/{name}',
                f'     overrides vs matrix: ' + ('ILLUSTRATIVE (see entry())' if i.startswith('S6') else 'verbatim campaign_entry')]
        cells = []
        for r in REF[i]:
            a, b = txt[r].splitlines(), txt[i].splitlines()
            dl = [l for l in difflib.unified_diff(a, b, lineterm='', n=0) if not l.startswith(('---', '+++', '@@'))]
            st = [l for l in dl if not l[1:].lstrip().startswith('#')]
            rep += [f'  --- vs {r}: {len(dl)} differing lines ({len(st)} solver statements, {len(dl) - len(st)} comments)'] + ['    ' + l for l in dl]
            cells.append(f'{r}: {len(st)} stmt / {len(dl) - len(st)} comment')
        summary.append(f'{n:2d} {i:10s} {e["thickness"]:>5} nm  ' + '; '.join(cells))
    # structural checks the register needs (REG-001 V_D steps, Qf on/off, AFF = affinity only, S2-11 = oxide mesh only)
    def stmts(i): return ct.statements(txt[i])
    for i, qf in (('S2-14', True), ('S2-15', True), ('S2-16', False), ('S2-17', False), ('STRIP-6p3', True)):
        s = stmts(i)
        if 'solve vstep=0.05 vfinal=0.1 name=drain' not in s or 'solve vstep=0.1 vfinal=0.7 name=drain' not in s: bad.append(f'{i}: V_D steps 0->0.1->0.7 missing')
        q = [l for l in s if l.startswith('interface qf=')]
        if len(q) != 1 or (q[0].startswith('interface qf=0 ') == qf): bad.append(f'{i}: Qf {"on" if qf else "off"} expected, got {q}')
        if any(l.startswith(('electrode name=gate', 'contact name=gate')) for l in s): bad.append(f'{i}: strip deck has a gate')
    for i, b in (('AFF-2p0', 'S0-01'), ('AFF-6p3', 'S1-01')):
        d = [(x, y) for x, y in zip(stmts(b), stmts(i)) if x != y]
        ok = len(stmts(b)) == len(stmts(i)) and len(d) == 1 and re.sub(r'affinity=\S+', '', d[0][0]) == re.sub(r'affinity=\S+', '', d[0][1])
        if not ok: bad.append(f'{i}: differs from {b} beyond the affinity value: {d}')
        else: summary.append(f'   {i}: only statement change vs {b}: "{d[0][0].strip()}" -> "{d[0][1].strip()}"')
    d = [(x, y) for x, y in zip(stmts('S0-02'), stmts('S2-11')) if x != y]
    if len(stmts('S0-02')) != len(stmts('S2-11')) or not all(x.startswith('y.mesh loc=0.0') and y.startswith('y.mesh loc=0.0') for x, y in d) or len(d) != 2:
        bad.append(f'S2-11: differs from S0-02 beyond the two oxide y.mesh lines: {d}')
    else: summary.append('   S2-11: only statement changes vs S0-02: ' + '; '.join(f'"{x}" -> "{y}"' for x, y in d))
    if any(re.match(r'qt[xy]\.mesh', l) for l in stmts('S2-11')): bad.append('S2-11: QT mesh present (automatic slicing expected)')
    rep += ['', 'CHECKS: ' + ('all passed' if not bad else '; '.join(bad))]
    (OUT / 'deck_diffs.txt').write_text('\n'.join(rep) + '\n', encoding='utf-8')
    print('\n'.join(summary)); print('decks written:', len(DIAG), '->', OUT); print('checks:', 'all passed' if not bad else bad)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
